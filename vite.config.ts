import { defineConfig, type Plugin, type ResolvedConfig, type Rollup } from 'vite';
import react from '@vitejs/plugin-react';

// Files in public/ that the offline app must have. They are copied by Vite, not bundled by
// Rollup, so they never show up in `bundle`. Listed here so they are precached even if the
// public/ folder cannot be read at build time.
const REQUIRED_PUBLIC_FILES = [
  'manifest.webmanifest',
  'icons/icon-192.png',
  'icons/icon-512.png',
  'icons/icon-maskable-512.png',
];

const SW_FILE = 'sw.js';
const CACHE_PREFIX = 'onething-precache-';

// Files that must never be precached (OS junk, source maps, the worker itself).
function skipFile(path: string): boolean {
  const name = path.slice(path.lastIndexOf('/') + 1);
  return (
    name.startsWith('.') ||
    name === 'Thumbs.db' ||
    name === 'desktop.ini' ||
    path.endsWith('.map') ||
    path === SW_FILE ||
    path.startsWith('.vite/')
  );
}

// FNV-1a, 32 bit. Only used to name the cache, so a tiny pure-JS hash is enough
// (no node:crypto, so this file type-checks without @types/node).
function fnv1a(bytes: Uint8Array, seed = 0x811c9dc5): number {
  let h = seed;
  for (let i = 0; i < bytes.length; i++) {
    h ^= bytes[i];
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h;
}

const encoder = new TextEncoder();
const toBytes = (source: string | Uint8Array): Uint8Array =>
  typeof source === 'string' ? encoder.encode(source) : source;
const hex = (n: number): string => n.toString(16).padStart(8, '0');

// Font name without hash and extension, e.g. "atkinson-hyperlegible-latin-400-normal".
// Uses Rollup's original asset name; falls back to stripping Vite's "-<8 char hash>".
function fontBaseName(fileName: string, output: Rollup.OutputAsset | Rollup.OutputChunk): string {
  const original = output.type === 'asset' ? output.names?.[0] : undefined;
  const base = original ?? fileName.slice(fileName.lastIndexOf('/') + 1).replace(/-[\w-]{8}(\.woff2?)$/, '$1');
  return base.replace(/\.woff2?$/, '');
}

// All files under public/, as paths relative to it with forward slashes.
async function listPublicFiles(fs: Rollup.RollupFsModule, root: string, sub = ''): Promise<string[]> {
  const entries = await fs.readdir(sub ? `${root}/${sub}` : root, { withFileTypes: true });
  const files: string[] = [];
  for (const entry of entries) {
    const rel = sub ? `${sub}/${entry.name}` : entry.name;
    if (entry.isDirectory()) files.push(...(await listPublicFiles(fs, root, rel)));
    else if (entry.isFile() && !skipFile(rel)) files.push(rel);
  }
  return files;
}

function serviceWorkerSource(cacheName: string, precache: string[]): string {
  return `/* One Thing service worker. Generated by vite.config.ts at build time. Do not edit. */
'use strict';
const CACHE_PREFIX = ${JSON.stringify(CACHE_PREFIX)};
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE = ${JSON.stringify(precache, null, 2)};
const INDEX_URL = new URL('./index.html', self.location.href).href;
const ROOT_URL = new URL('./', self.location.href).href;
// Page paths that open the app (query and hash are ignored): ./ and ./index.html
const SHELL_PATHS = [new URL(ROOT_URL).pathname, new URL(INDEX_URL).pathname];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE.map((url) => new Request(url, { cache: 'reload' }))))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME)
            .map((key) => caches.delete(key))
        )
      )
      .then(() => self.clients.claim())
  );
});

// A redirected response cannot answer a navigation, so copy it into a plain one.
function plain(response) {
  if (!response.redirected) return Promise.resolve(response);
  return response.blob().then(
    (body) =>
      new Response(body, { status: response.status, statusText: response.statusText, headers: response.headers })
  );
}

// The app shell from this worker's cache: ./index.html, else ./ (undefined if neither is there).
function cachedShell() {
  return caches
    .open(CACHE_NAME)
    .then((cache) =>
      cache.match(INDEX_URL, { ignoreVary: true }).then((hit) => hit || cache.match(ROOT_URL, { ignoreVary: true }))
    )
    .then((hit) => (hit ? plain(hit) : undefined))
    .catch(() => undefined);
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // Opening the app: answer from the cached shell at once (app-shell pattern). It never waits
  // for the network, so weak signal or a host error page cannot hide the app. The cached
  // index.html always matches the cached assets of this worker version. A new deploy arrives as
  // a new sw.js with a new cache and shows on the next launch. Network only if the shell is missing.
  // Other page paths are not app pages, so the browser handles them as usual.
  if (request.mode === 'navigate') {
    if (SHELL_PATHS.includes(url.pathname)) {
      event.respondWith(cachedShell().then((hit) => hit || fetch(request)));
    }
    return;
  }

  if (url.href === self.location.href || request.headers.has('range')) return;

  // Assets (hashed JS/CSS/fonts, manifest, icons): cache first, network as a fallback.
  event.respondWith(
    caches.open(CACHE_NAME).then((cache) =>
      cache.match(request, { ignoreVary: true }).then((hit) => {
        if (hit) return hit;
        return fetch(request).then((response) => {
          if (response.ok && response.type === 'basic') {
            event.waitUntil(cache.put(request, response.clone()).catch(() => undefined));
          }
          return response;
        });
      })
    )
  );
});
`;
}

// Emits sw.js on generateBundle. Precache = ./, ./index.html, every public/ file (manifest,
// icons) and every file Rollup emitted (minus .woff files that have a .woff2 twin). Cache name = prefix + hash of that list, where each
// entry carries a hash of its content, so any changed file gives a new cache and a new sw.js.
function oneThingServiceWorker(): Plugin {
  let publicDir = '';
  return {
    name: 'one-thing-service-worker',
    apply: 'build',
    enforce: 'post', // run after Vite's HTML plugin, so index.html is already in the bundle
    configResolved(config: ResolvedConfig) {
      publicDir = config.build.copyPublicDir && config.publicDir ? config.publicDir : '';
    },
    async generateBundle(_options, bundle) {
      const contentHash = new Map<string, string>();
      const entries = Object.entries(bundle).filter(([fileName]) => !skipFile(fileName));

      // Chrome only uses .woff2, so a .woff whose .woff2 sibling (same original name, different
      // hash) is in the bundle is never fetched: leave it out of the precache.
      const woff2Names = new Set(
        entries.filter(([fileName]) => fileName.endsWith('.woff2')).map(([f, o]) => fontBaseName(f, o)),
      );

      for (const [fileName, output] of entries) {
        if (fileName.endsWith('.woff') && woff2Names.has(fontBaseName(fileName, output))) continue;
        const source = output.type === 'chunk' ? output.code : output.source;
        contentHash.set(fileName, hex(fnv1a(toBytes(source))));
      }

      // Rollup >= 4.36 gives plugins `this.fs`; the guard keeps older Rollup builds working.
      const fs: Rollup.RollupFsModule | undefined = this.fs;
      let publicFiles: string[] = [];
      if (publicDir && fs) {
        try {
          publicFiles = await listPublicFiles(fs, publicDir);
          for (const rel of publicFiles) {
            contentHash.set(rel, hex(fnv1a(await fs.readFile(`${publicDir}/${rel}`))));
          }
        } catch (err) {
          this.warn(`could not read public/ for the precache list: ${String(err)}`);
        }
      }
      for (const rel of REQUIRED_PUBLIC_FILES) {
        if (fs && publicDir && !publicFiles.includes(rel)) {
          this.warn(`${rel} is missing from public/, so the service worker will fail to install`);
        }
        if (!contentHash.has(rel)) contentHash.set(rel, 'unread');
      }

      const files = [...contentHash.keys()].filter((f) => f !== 'index.html').sort();
      const precache = ['./', './index.html', ...files.map((f) => `./${f}`)];
      const fingerprint = ['./', 'index.html', ...files]
        .map((f) => `${f}:${contentHash.get(f) ?? ''}`)
        .join('\n');
      const cacheName = `${CACHE_PREFIX}${hex(fnv1a(encoder.encode(fingerprint)))}`;

      this.emitFile({ type: 'asset', fileName: SW_FILE, source: serviceWorkerSource(cacheName, precache) });
    },
  };
}

// base './' = relative asset paths, so the build works from any static host (personal Vercel at gate 10).
export default defineConfig({
  base: './',
  plugins: [react(), oneThingServiceWorker()],
});
